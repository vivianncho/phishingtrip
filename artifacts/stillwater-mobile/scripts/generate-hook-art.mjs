import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

export const layerNames = ['fins', 'body', 'face', 'lantern'];
const canvasUrl = new URL('../../mockup-sandbox/src/components/mockups/stillwater/Stillwater.tsx', import.meta.url);
const sourcesUrl = new URL('../../mockup-sandbox/public/images/', import.meta.url);
const outputUrl = new URL('../components/hookArt.ts', import.meta.url);

// Parse the actual JSX rather than maintaining a second set of coordinates.
export function canvasPlacement(canvas) {
  const ast = ts.createSourceFile('Stillwater.tsx', canvas, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  if (ast.parseDiagnostics.length) throw new Error('Canvas JSX could not be parsed; fix it before regenerating Hook');
  const placements = {};
  let viewBox;
  function literalAttributes(node) {
    return Object.fromEntries(node.attributes.properties.filter(ts.isJsxAttribute)
      .filter(attr => attr.initializer && ts.isStringLiteral(attr.initializer))
      .map(attr => [attr.name.getText(ast), attr.initializer.text]));
  }
  function visit(node, parentViewBox) {
    const opening = ts.isJsxElement(node) ? node.openingElement : node;
    let currentViewBox = parentViewBox;
    if (ts.isJsxOpeningElement(opening) || ts.isJsxSelfClosingElement(opening)) {
      const attrs = literalAttributes(opening);
      const tag = opening.tagName.getText(ast);
      if (tag === 'svg') currentViewBox = attrs.viewBox;
      if (tag === 'image') {
        const name = layerNames.find(name => attrs.href?.endsWith(`/hook-figma-${name}.svg`));
        if (name) {
          if (placements[name]) throw new Error(`Duplicate canvas layer: ${name}`);
          if (!currentViewBox || (viewBox && viewBox !== currentViewBox)) throw new Error('Hook layers must share one literal canvas viewBox');
          viewBox = currentViewBox;
          placements[name] = Object.fromEntries(['x', 'y', 'width', 'height'].map(key => {
            if (!attrs[key] || !Number.isFinite(Number(attrs[key]))) throw new Error(`Missing literal ${key} for ${name}`);
            if (['width', 'height'].includes(key) && Number(attrs[key]) <= 0) throw new Error(`Invalid ${key} for ${name}`);
            return [key, attrs[key]];
          }));
        }
      }
    }
    // Opening elements are already handled above.
    ts.forEachChild(node, child => {
      if (ts.isJsxElement(node) && child === node.openingElement) return;
      visit(child, currentViewBox);
    });
  }
  visit(ast);
  for (const name of layerNames) if (!placements[name]) throw new Error(`Missing canvas layer: ${name}`);
  const bounds = viewBox?.trim().split(/[\s,]+/).map(Number);
  if (bounds?.length !== 4 || !bounds.every(Number.isFinite) || bounds[2] <= 0 || bounds[3] <= 0) {
    throw new Error('Hook canvas viewBox must contain four finite numbers with positive dimensions');
  }
  return { viewBox, placements };
}

export function nativeLayer(source, placement, name) {
  const match = source.trim().match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>$/);
  if (!match) throw new Error(`Expected a complete SVG root for ${name}`);
  let [, attributes, contents] = match;
  // Figma's browser-only presentation attributes are replaced by the canvas viewport.
  attributes = attributes.replace(/\s+(?:x|y|width|height|preserveAspectRatio|overflow|style)="[^"]*"/g, '');
  if (!/\bviewBox="[^"]+"/.test(attributes)) throw new Error(`Missing SVG viewBox for ${name}`);
  if (name === 'lantern') {
    // Only the lantern's browser filter is substituted. Hook.tsx owns the native glow circles.
    contents = contents.replace(/<filter\b[^>]*>[\s\S]*?<\/filter>/g, '')
      .replace(/\s+filter="[^"]*"/g, '')
      .replace(/<defs>\s*<\/defs>/g, '');
  }
  const xml = `<svg ${Object.entries(placement).map(([key, value]) => `${key}="${value}"`).join(' ')}${attributes}>${contents}</svg>`
    .replace(/>\s+</g, '> <').trim();
  if (/(?:\b(?:href|filter|style)=|<image\b|<filter\b|<fe[A-Z]|<script\b|<foreignObject\b|\bon\w+=)/i.test(xml)) {
    throw new Error(`Unsupported browser content in ${name}; review native artwork conversion`);
  }
  return xml;
}

export function generateHookArt(sources, canvas) {
  const { viewBox, placements } = canvasPlacement(canvas);
  // Include raw sources so even changes to substituted filters require regeneration/review.
  const orderedSources = Object.fromEntries(layerNames.map(name => [name, sources[name]]));
  const digest = createHash('sha256').update(JSON.stringify({ sources: orderedSources, viewBox, placements })).digest('hex');
  const lines = [
    '// GENERATED by pnpm --filter @workspace/stillwater-mobile run generate:hook-art — do not edit.',
    '// Sources: artifacts/mockup-sandbox/public/images/hook-figma-{fins,body,face,lantern}.svg',
    '// Placement: Stillwater.tsx canvas. Paths, fills and strokes are preserved.',
    '// Lantern browser filter is replaced by native glow circles in components/Hook.tsx.',
    `// Source SHA-256: ${digest}`,
    ...layerNames.map(name => `export const HOOK_${name.toUpperCase()} = ${JSON.stringify(nativeLayer(sources[name], placements[name], name))};`),
    `export const hookXml = (layers: string[]) => \`<svg viewBox="${viewBox}" fill="none" xmlns="http://www.w3.org/2000/svg">\${layers.join("")}</svg>\`;`,
  ];
  return `${lines.join('\n')}\n`;
}

export async function regenerateHookArt({
  sourceDir = sourcesUrl, canvasPath = canvasUrl, outputPath = outputUrl, check = false,
} = {}) {
  const sources = Object.fromEntries(await Promise.all(layerNames.map(async name =>
    [name, await readFile(new URL(`hook-figma-${name}.svg`, sourceDir), 'utf8')])));
  const generated = generateHookArt(sources, await readFile(canvasPath, 'utf8'));
  const existing = await readFile(outputPath, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (existing === generated) return false;
  if (check) throw new Error('Mobile Hook artwork is stale. Run pnpm --filter @workspace/stillwater-mobile run generate:hook-art');
  await writeFile(outputPath, generated);
  return true;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  try {
    if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: generate-hook-art.mjs [--check]');
    const changed = await regenerateHookArt({ check: process.argv.includes('--check') });
    console.log(changed ? `Regenerated ${fileURLToPath(outputUrl)}` : 'Mobile Hook artwork is up to date.');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
